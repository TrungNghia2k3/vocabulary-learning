            lookup?.paraKey === paraKey &&
            typeof lookup.wordStartIdx === 'number' &&
            typeof lookup.wordEndIdx === 'number' &&
            myWordIdx >= lookup.wordStartIdx &&
            myWordIdx <= lookup.wordEndIdx;

